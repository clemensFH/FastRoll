/**
 * Generates packages/common/src/abi.ts from the compiled Foundry artifacts.
 *
 * Hand-written ABIs drift. The previous arc lost an afternoon to a routerAbi
 * that was missing five functions the off-chain side actually called, and a
 * whole-workspace typecheck was the only thing that caught it. Generating them
 * makes that class of bug impossible.
 *
 * Run: pnpm abis   (after forge build)
 */
import { readFileSync, writeFileSync } from "node:fs";

const CONTRACTS = ["CourseToken", "Escrow", "Gateway", "Registry"] as const;
const ROOT = new URL("../../../", import.meta.url);

function abiOf(name: string): unknown[] {
  const path = new URL(`contracts/out/${name}.sol/${name}.json`, ROOT);
  const artifact = JSON.parse(readFileSync(path, "utf8")) as { abi: unknown[] };
  if (!artifact.abi?.length) throw new Error(`${name} has no ABI; run forge build first`);
  return artifact.abi;
}

let out = `/**
 * Contract ABIs. GENERATED by packages/common/scripts/gen-abis.ts.
 *
 * Do not edit. Run \`pnpm abis\` after changing a contract, so the off-chain
 * side cannot silently disagree with what is deployed.
 */

`;

for (const name of CONTRACTS) {
  const key = name.charAt(0).toLowerCase() + name.slice(1) + "Abi";
  out += `export const ${key} = ${JSON.stringify(abiOf(name), null, 2)} as const;\n\n`;
}

writeFileSync(new URL("packages/common/src/abi.ts", ROOT), out);
console.log(`  packages/common/src/abi.ts  (${CONTRACTS.length} contracts)`);
